const languages = ['en', 'zh', 'pt', 'fr', 'de', 'ru', 'ja', 'ar', 'it', 'ko', 'qu'];

for (const lang of languages) {
  console.log(`\nProcessing language: [${lang.toUpperCase()}]...`);
  // Fetch historical translations from b98d8d84
  let histDict = new Map();
  try {
    const histRaw = execSync(`git show b98d8d84:client/app/src/lib/i18n/locales/${lang}.ts`, { maxBuffer: 10 * 1024 * 1024 }).toString('utf8');
    histDict = extractDict(histRaw);
    console.log(`  Found ${histDict.size} historical translations in commit b98d8d84.`);
  } catch (e) {
    console.warn(`  Warning: Could not extract historical translations for ${lang}: ${e.message}`);
  }

  const newLangOverrides = NEW_TRANSLATIONS[lang] || {};

  // Generate language file by following the exact AST/structure of es.ts
  const outLines = [];
  outLines.push("import { I18nSchema } from './es';\n");
  outLines.push(`export const ${lang}: I18nSchema = {`);

  const keyStack = [];
  let braceDepth = 0;
  const sectionRe = /^(\s*)([\w]+)\s*:\s*\{\s*$/;
  const closingRe = /^(\s*)\},?\s*$/;
  const valueRe = /^(\s*)([\w]+)\s*:\s*(?:"((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)')\s*,?\s*$/;

  let started = false;
  for (let i = 0; i < esLines.length; i++) {
    const line = esLines[i].replace(/\r/, '');
    if (!started) {
      if (line.includes('export const es = {')) {
        started = true;
      }
      continue;
    }
    if (line.includes('export type I18nSchema')) {
      break;
    }

    const secMatch = line.match(sectionRe);
    if (secMatch) {
      keyStack.push(secMatch[2]);
      braceDepth++;
      outLines.push(`${secMatch[1]}${secMatch[2]}: {`);
      continue;
    }

    const closeMatch = line.match(closingRe);
    if (closeMatch && braceDepth > 0) {
      keyStack.pop();
      braceDepth--;
      outLines.push(line);
      continue;
    }

    const valMatch = line.match(valueRe);
    if (valMatch && braceDepth > 0) {
      const indent = valMatch[1];
      const propName = valMatch[2];
      const esValue = valMatch[3] !== undefined ? valMatch[3] : valMatch[4];
      const flatKey = [...keyStack, propName].join('.');

      // Priority:
      // 1. New translations defined in NEW_TRANSLATIONS[lang]
      // 2. Historical translation from commit b98d8d84
      // 3. Fallback to English if available in NEW_TRANSLATIONS.en
      let translatedValue = newLangOverrides[flatKey];
      if (!translatedValue && histDict.has(flatKey)) {
        translatedValue = histDict.get(flatKey);
      }
      if (!translatedValue) {
        translatedValue = NEW_TRANSLATIONS.en[flatKey] || esValue;
      }

      // Escape double quotes and backslashes properly
      const escaped = translatedValue.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
      outLines.push(`${indent}${propName}: "${escaped}",`);
      continue;
    }

    // Empty lines or comments
    if (line.trim() === '' || line.trim().startsWith('//')) {
      outLines.push(line);
    }
  }

  // Properly close the root object export
  outLines.push('};');

  const targetPath = path.join(LOCALES_DIR, `${lang}.ts`);
  fs.writeFileSync(targetPath, outLines.join('\n') + '\n', 'utf8');
  console.log(`  Successfully generated ${targetPath}`);
}

